from video_topics import esc, head, stage, hook, tile, END
from video_topics_yaku import note, scene, YAKU_END

TOPICS = {}

def tiles(cs, w=58, key=False):
    h = "".join(tile(c, round(w * 1.4) if "yoko" in c else w) for c in cs.split())
    return f'<span style="display:inline-flex;gap:2px;padding:5px;border-radius:12px;background:#E75620">{h}</span>' if key else f'<span style="display:inline-flex;gap:2px">{h}</span>'

def row(label, cs="", key="", cap="", w=58):
    body = (tiles(cs, w) if cs else "") + (tiles(key, w, True) if key else "")
    capd = f'<div style="font-size:34px;font-weight:700;color:#4F5C5A;margin-top:10px">{esc(cap)}</div>' if cap else ""
    return (f'<div style="padding:22px 0;border-top:3px dashed #D5DEDB"><div style="font-size:36px;font-weight:900;color:#177083;margin-bottom:12px">{esc(label)}</div>'
            f'<div style="display:flex;gap:14px;align-items:flex-end;flex-wrap:wrap">{body}</div>{capd}</div>')

def board(*rows):
    return '<div class="vcard" style="padding:6px 40px 18px;text-align:left">' + "".join(rows) + "</div>"

def han_tag(name, han):
    return f'<div class="mid"><span class="ans">{esc(name)}</span><div class="big" style="font-size:72px;color:#177083;margin-top:16px">{esc(han)}</div></div>'

H13 = "m1 m2 m3 m4 m5 m6 p7 p8 p9 s2 s3 s5 s5"

def mk(no, name, han, hook_lines, hook_title, vis_board, steps, cond_lines, cond_html):
    """steps = [(声, 見出し, 場面の板)]"""
    def f():
        out = [(hook_lines, hook("状況で決まる役", hook_title, vis_board))]
        for lines, ttl, bd in steps:
            out.append((lines, scene(ttl, (.3, 360, bd))))
        out.append((cond_lines, scene("まとめ", (.2, 360, han_tag(name, han)), (1.0, 700, cond_html))))
        out.append(YAKU_END)
        return out
    TOPICS[f"ys-{no:02d}"] = f

