KEYS = "ABCD"
def opts(items, a, step=.6, d0=.6):
    """items = [(見出し, 説明)]。A・B・C の札で順に出す"""
    out = ""
    for i, (t, dsc) in enumerate(items):
        out += (f'<div class="o" data-in="{a + d0 + i * step:.2f}" data-a="left"><span class="k" style="{"background:#E75620" if i % 2 else ""}">{KEYS[i]}</span>'
                f'<div><div class="t">{t}</div>' + (f'<div class="d">{dsc}</div>' if dsc else "") + "</div></div>")
    return f'<div class="opt">{out}</div>'

def q(title, sub, items, extra=None, top=330):
    """「決めること」の場面: 見出し → 選択肢 → ひとこと"""
    def mk(a, b):
        els = [head(a, b, title)]
        y = top
        if sub:
            els.append(stage(a + .1, b, sub, top=y)); y += 210
        els.append(stage(a + .2, b, opts(items, a), top=y))
        if extra:
            d, t_, h = extra
            els.append(stage(a + d, b, h, top=t_))
        return els
    return mk

def checklist(items, a, step=.6):
    out = ""
    for i, t in enumerate(items):
        t0 = a + .5 + i * step
        out += (f'<div class="chk"><i style="position:relative"><span data-in="{t0:.2f}" data-a="pop" style="position:absolute;inset:-5px;display:grid;place-items:center;'
                f'background:#177083;border-radius:16px;color:#fff;font-size:46px">✓</span></i>{t}</div>')
    return f'<div class="tbl" style="padding:6px 36px">{out}</div>'

