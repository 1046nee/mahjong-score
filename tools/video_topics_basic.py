def sc(title, *parts):
    def mk(a, b):
        els = [head(a, b, title)]
        for p in parts:
            d, t, h = p[:3]
            els.append(stage(a + d, b, h, top=t, anim=p[3] if len(p) > 3 else "up"))
        return els
    return mk

def card(rows, size=48):
    """[(左, 右)] の白い表。右に色をつけたいときは ('+61.3', 'pos') のように"""
    out = ""
    for l, r in rows:
        txt, cl = (r if isinstance(r, tuple) else (r, ""))
        col = {"pos": "#1A237E", "neg": "#C62828", "o": "#E75620", "": "#1F2A28"}[cl]
        out += f'<tr><td style="font-size:{size - 6}px">{l}</td><td class="r" style="font-size:{size}px;color:{col}">{txt}</td></tr>'
    return f'<div class="vcard"><table class="vt">{out}</table></div>'

def grid(head_, rows, a=None, step=.5, hl_col=None):
    """列のある表。rows = [[セル…]]。a を渡すと1行ずつ出る"""
    n = len(head_)
    cols = "190px " + " ".join(["1fr"] * (n - 1))
    out = f'<div style="display:grid;grid-template-columns:{cols};gap:6px;font-size:32px;font-weight:900;color:#5F6E6B;padding:10px 0">' + "".join(f'<span style="text-align:{"left" if i == 0 else "right"}">{h}</span>' for i, h in enumerate(head_)) + "</div>"
    for k, r in enumerate(rows):
        attr = f' data-in="{a + .4 + k * step:.2f}" data-a="left"' if a is not None else ""
        cells = ""
        for i, c in enumerate(r):
            col = "#1F2A28"
            if i > 0 and isinstance(c, str) and c[:1] in "+−-": col = "#1A237E" if c[0] == "+" else "#C62828"
            if hl_col is not None and i == hl_col: col = "#E75620" if col == "#1F2A28" else col
            cells += f'<span style="text-align:{"left" if i == 0 else "right"};{"font-size:46px" if i == n - 1 else ""};color:{col}">{c}</span>'
        out += f'<div{attr} style="display:grid;grid-template-columns:{cols};gap:6px;align-items:center;height:100px;border-top:3px solid #E3E9E7;font-size:40px;font-weight:900">{cells}</div>'
    return f'<div class="tbl" style="padding:6px 30px">{out}</div>'

def big(tx, color="#E75620", size=110):
    return f'<div class="mid"><div class="big" style="font-size:{size}px;color:{color}">{tx}</div></div>'

def ok_ng(ok, tx):
    return f'<span class="{"ok" if ok else "ng"}" style="font-size:42px">{tx}</span>'

