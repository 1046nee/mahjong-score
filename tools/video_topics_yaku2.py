def B(rows, size=48):
    """箇条書き。rows = [(○ / × / 数字 / None, 文)]"""
    out = ""
    for mk, tx in rows:
        t = "" if mk is None else tag(mk != "×", mk) + "　"
        out += f'<div class="yk" style="margin:22px 0;font-size:{size}px">{t}{tx}</div>'
    return f'<div class="vcard">{out}</div>'

def T(rows):
    return '<div class="vcard">' + vt3(rows) + "</div>"

def pill(tx, bg="#E75620", size=60):
    return f'<div class="mid"><span class="ans" style="background:{bg};font-size:{size}px">{tx}</span></div>'

def trow(codes, w=70, dim=(), red=()):
    out = ""
    for i, c in enumerate(codes):
        st = "opacity:.22;" if i in dim else ""
        if i in red: st += "outline:6px solid #C62828;outline-offset:2px;border-radius:8px;"
        out += f'<span style="display:inline-block;{st}">{tile(c, w)}</span>'
    return f'<div class="trow" style="gap:4px;justify-content:center">{out}</div>'

def plus(rows, total):
    """翻の足し算。rows = [(役, 翻)]"""
    r = "".join(f'<tr><td>{esc(a)}</td><td class="r">{esc(b)}</td></tr>' for a, b in rows)
    return f'<div class="vcard"><table class="vt">{r}<tr><td style="color:#E75620">合計</td><td class="r" style="color:#E75620;font-size:56px">{esc(total)}</td></tr></table></div>'

def quiz(i, groups, win, melds=None):
    """最初の2場面（問題と答え）"""
    y = _Y[i - 1]
    g = list(groups) + ([("", m) for m in melds] if melds else [])
    vis = hand(g, 60 if len(g) > 5 else 60, win=win)
    def ans(a, b):
        return [head(a, b, "答え"), stage(a + .2, b, vis, top=380, anim="fade"),
                stage(a + .6, b, f'<div class="mid"><div class="big" style="font-size:110px;color:#177083">{esc(y["name"])}</div><p class="lbl" style="font-size:50px">{esc(y["read"])}</p><span class="ans" style="font-size:58px">{esc(y["han"])}</span></div>', top=760, anim="pop")]
    han_say = y["han"].replace("（", "、").replace("）", "")
    return vis, [(["この手、", "何の役かわかる？"], hook(f"役シリーズ {i}/{N}", "この手、\n何の役？", vis)),
                 ([f"答えは、{y['read']}。", han_say + "。"], ans)]

